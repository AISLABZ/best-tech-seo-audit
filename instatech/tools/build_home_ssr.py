"""Build wp-content/mu-plugins/instatech-home-ssr.php from a live capture of the homepage.

The homepage builds five sections in the browser from JavaScript arrays (repair tiles, accessory categories, two
product rails, reviews); the server sends them as empty <div>s, so crawlers that don't run JavaScript miss that content
and its links. The generated plugin puts the captured HTML into those containers on the server. The page's own script
still runs and rewrites the same content, so nothing changes for visitors.

Fail-safe: the plugin only injects while the homepage script is unchanged (fingerprint below). If anyone edits those
sections, the fingerprint no longer matches and the page falls back to today's behaviour. Re-run this build to refresh.

Usage:
  node instatech/tools/capture_home_sections.js <playwright-core> <chromium> <dir>
  python3 instatech/tools/build_home_ssr.py <dir>
"""
import hashlib
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDS = ["tiles", "cats", "audio", "chargers", "rvgrid"]
MARKER = "CATURL"


def homepage_script(html):
    """Inner text of the inline <script> that renders the sections (the one defining CATURL)."""
    at = html.find(MARKER)
    if at < 0:
        sys.exit("homepage script not found")
    open_tag = html.rfind("<script", 0, at)
    start = html.find(">", open_tag) + 1
    end = html.find("</script>", at)
    return html[start:end]


def fingerprint(script):
    # LiteSpeed rewrites <iframe>/<img> tags for lazy-loading and trims whitespace around the script after WordPress
    # renders the page, so those are normalised; everything else must match exactly.
    norm = re.sub(r"<iframe[^>]*>", "<iframe>", script.strip())
    norm = re.sub(r"<img[^>]*>", "<img>", norm)
    return hashlib.sha1(norm.encode("utf-8")).hexdigest()


def main(capture_dir):
    capture = Path(capture_dir)
    sections = json.loads((capture / "home-sections.json").read_text())
    raw = (capture / "home-raw.html").read_text(encoding="utf-8")
    fp = fingerprint(homepage_script(raw))

    for i in IDS:
        if not sections.get(i):
            sys.exit(f"section {i} missing from capture")
        if raw.count(f'id="{i}"></div>') != 1:
            sys.exit(f"container {i} is not a single empty div in the raw HTML")
        if "INSTATECH_SSR" in sections[i]:
            sys.exit("nowdoc terminator collides with content")

    entries = "\n".join(
        f"\t\t'{i}' => <<<'INSTATECH_SSR'\n{sections[i]}\nINSTATECH_SSR,"
        for i in IDS
    )
    php = f"""<?php
/**
 * Plugin Name: InstaTech homepage server-side sections
 * Description: Server-renders the five homepage sections that are otherwise built only in the browser (repair tiles,
 *              accessory categories, audio and charger rails, reviews), so search engines and AI crawlers see their
 *              content and links without running JavaScript. The page script still runs and rewrites the same HTML.
 *              Fail-safe: injects only while the homepage script matches the captured fingerprint; any edit to those
 *              sections switches this off automatically. Generated by instatech/tools/build_home_ssr.py on {date.today()}.
 *              Roll back by replacing this file with an empty one.
 */

defined( 'ABSPATH' ) || exit;

function instatech_home_ssr_fingerprint( $script ) {{
	$norm = preg_replace( '#<iframe[^>]*>#', '<iframe>', trim( $script ) );
	$norm = preg_replace( '#<img[^>]*>#', '<img>', $norm );
	return sha1( $norm );
}}

function instatech_home_ssr_sections() {{
	return array(
{entries}
	);
}}

function instatech_home_ssr( $html ) {{
	if ( ! is_string( $html ) ) {{
		return $html;
	}}
	$at = strpos( $html, '{MARKER}' );
	if ( false === $at ) {{
		return $html;
	}}
	$open  = strrpos( substr( $html, 0, $at ), '<script' );
	$start = false === $open ? false : strpos( $html, '>', $open );
	$end   = strpos( $html, '</script>', $at );
	if ( false === $start || false === $end ) {{
		return $html;
	}}
	$script = substr( $html, $start + 1, $end - $start - 1 );
	if ( '{fp}' !== instatech_home_ssr_fingerprint( $script ) ) {{
		// Record what the plugin saw, once, so a mismatch can be diagnosed (wp-content/instatech-ops/).
		$dir = WP_CONTENT_DIR . '/instatech-ops';
		$seen = instatech_home_ssr_fingerprint( $script );
		$file = $dir . '/home-ssr-mismatch-' . $seen . '.txt';
		if ( ! file_exists( $file ) && wp_mkdir_p( $dir ) ) {{
			file_put_contents( $file, $script );
		}}
		return $html;
	}}
	foreach ( instatech_home_ssr_sections() as $id => $inner ) {{
		$empty = 'id="' . $id . '"></div>';
		if ( 1 === substr_count( $html, $empty ) ) {{
			$html = str_replace( $empty, 'id="' . $id . '">' . $inner . '</div>', $html );
		}}
	}}
	return $html;
}}

add_action(
	'template_redirect',
	function () {{
		if ( is_admin() || is_feed() || wp_doing_ajax() || ! is_front_page() ) {{
			return;
		}}
		ob_start( 'instatech_home_ssr' );
	}},
	3
);
"""
    out = ROOT / "wp" / "mu-plugins" / "instatech-home-ssr.php"
    out.write_text(php)
    print(f"fingerprint {fp}; {sum(len(sections[i]) for i in IDS)} bytes of section HTML -> {out.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main(sys.argv[1])
