def root(t):
    lines = [f"color-scheme:{t['scheme']};"]
    lines += [f"--{k}:{v};" for k, v in t.items() if k != "scheme"]
    # grouped 4 per line for readability
    out = []
    for i in range(0, len(lines), 6):
        out.append("  " + "".join(lines[i:i + 6]))
    return ":root{\n" + "\n".join(out) + "\n  --head:'Bricolage Grotesque',system-ui,sans-serif;--body:'Source Sans 3',system-ui,sans-serif;\n}"

